public class lecture_8 {
    public static void main(String[] args) {
        //iteration statements 

        //while loop
        int i =1;
        while(i<=10){
            System.out.println(i);
            i++;
        }

        //do while loop
        int j =0;
        do{
            System.out.println("welcome");
            System.out.println(j);
            j++;
        }while(j<=10);

        //for loop
        int k;
        for(k=1;k<=10;k++){
            System.out.println(k);
        }
    }
}
