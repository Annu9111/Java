public class lecture_8 {
    public static void main(String[] args) {
        //iteration statements 
        int i =1;
        while(i<=10){
            System.out.println(i);
            i++;
        }

        int j =0;
        do{
            System.out.println("welcome");
            System.out.println(j);
            j++;
        }while(j<=10);
    }
}
